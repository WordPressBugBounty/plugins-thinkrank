<?php
/**
 * Serves the sitemap XSL stylesheets, branded with the site's own logo and colours.
 *
 * @package ThinkRank
 * @since   2.7.0
 */

declare(strict_types=1);

namespace ThinkRank\SEO;

if (!defined('ABSPATH')) {
    exit;
}

/**
 * The browser-facing stylesheet for published sitemaps.
 *
 * Until 2.7.0 the `<?xml-stylesheet?>` instruction pointed straight at
 * `static/xsl/sitemap.xsl`, a file the web server hands over untouched. That is
 * why the sitemap could not be branded: nothing of ours runs on that request,
 * so no setting could reach it. The instruction now points here instead, and
 * this answers it from PHP with the stored palette substituted in.
 *
 * Three consequences worth keeping in mind when changing any of this:
 *
 *   - **The .xsl files stay complete and stock.** They are read as templates,
 *     but every brandable colour in them is a CSS custom property holding the
 *     value it has always held, so a sitemap still pointing at the old static
 *     URL renders exactly as it did. Substitution only ever overwrites a
 *     custom property declaration; it never introduces one.
 *   - **Colour changes need no regeneration.** The published XML holds a fixed
 *     URL, and the palette is read per request, so saving a colour is visible
 *     immediately on sitemaps written months ago.
 *   - **The URL is a query string on the home URL, not a pretty path.** A path
 *     only reaches WordPress when the rewrite rules send it there, which on an
 *     Apache-style host running Plain permalinks they do not. The same trap
 *     Instant Indexing documents for its key file (#247).
 *
 * @since 2.7.0
 */
class Sitemap_Stylesheet {

    /**
     * Query variable naming the stylesheet to serve.
     *
     * @since 2.7.0
     * @var string
     */
    public const QUERY_VAR = 'thinkrank_sitemap_xsl';

    /**
     * Query variable naming the sitemap document whose HTML view to serve.
     *
     * Browsers are removing XSLT (Chrome 158 stops running it on Stable), so
     * the styled table can no longer be left to the browser. This view renders
     * the same stylesheet on the server and answers with plain HTML, at its own
     * URL so the sitemap URLs, their bytes for crawlers and their Content-Type
     * stay exactly as they were. Static delivery serves those files without
     * PHP, which is the other reason the view cannot live at the sitemap URL.
     *
     * @since 2.18.0
     * @var string
     */
    public const VIEW_QUERY_VAR = 'thinkrank_sitemap_view';

    /**
     * Transient prefix for a rendered view, one entry per document.
     *
     * @since 2.18.0
     * @var string
     */
    private const VIEW_CACHE_PREFIX = 'thinkrank_sitemap_view_';

    /**
     * How long a rendered view is kept. The fingerprint already retires it
     * as soon as the sitemap or its branding changes; this only bounds how
     * long the entry of a document nobody asks for any more stays stored.
     *
     * @since 2.18.0
     * @var int
     */
    private const VIEW_CACHE_TTL = DAY_IN_SECONDS;

    /**
     * Sitemap XML namespace.
     *
     * @since 2.18.0
     * @var string
     */
    private const SITEMAP_NS = 'http://www.sitemaps.org/schemas/sitemap/0.9';

    /**
     * Stylesheet variants, mapped to their template basename.
     *
     * @since 2.7.0
     * @var array<string, string>
     */
    private const VARIANTS = [
        'sitemap' => 'sitemap.xsl',
        'index'   => 'sitemap-index.xsl',
    ];

    /**
     * The stock palette, mirroring the `:root` block in both templates.
     *
     * Used to answer "what does an unset colour look like?" for the settings
     * screen. The templates remain the source of truth for rendering: an unset
     * colour substitutes nothing at all, rather than substituting these.
     *
     * @since 2.7.0
     * @var array<string, string>
     */
    public const STOCK_PALETTE = [
        'main'   => '#667eea',
        'accent' => '#764ba2',
    ];

    /**
     * Where the logo goes in the rendered header.
     *
     * An XSLT processor strips stylesheet comments from its output, so this
     * marker costs a site with no logo nothing: served un-substituted, it
     * simply never reaches the page.
     *
     * @since 2.7.0
     * @var string
     */
    private const LOGO_MARKER = '<!-- thinkrank:logo -->';

    /**
     * Prefix on every line that prints the "Generated by" credit.
     *
     * @since 2.15.0
     * @var string
     */
    private const CREDIT_MARKER = '<!-- thinkrank:credit -->';

    /**
     * Register the request handler.
     *
     * @since 2.7.0
     * @return void
     */
    public function init(): void {
        add_filter('query_vars', [$this, 'register_query_var']);
        add_action('parse_request', [$this, 'maybe_serve']);
        add_action('parse_request', [$this, 'maybe_serve_view']);
    }

    /**
     * Declare the query variable so WordPress keeps it.
     *
     * @since 2.7.0
     * @param string[] $vars Registered public query vars.
     * @return string[]
     */
    public function register_query_var(array $vars): array {
        $vars[] = self::QUERY_VAR;
        $vars[] = self::VIEW_QUERY_VAR;

        return $vars;
    }

    /**
     * The URL a published sitemap points its `<?xml-stylesheet?>` at.
     *
     * Single source of truth: the prolog writer and the request matcher below
     * both derive from this, so they cannot drift.
     *
     * @since 2.7.0
     * @param string $variant One of the VARIANTS keys.
     * @return string Absolute stylesheet URL.
     */
    public static function url(string $variant): string {
        if (!isset(self::VARIANTS[$variant])) {
            $variant = 'sitemap';
        }

        return add_query_arg(self::QUERY_VAR, $variant, home_url('/'));
    }

    /**
     * The URL of a sitemap document's server-rendered HTML view.
     *
     * @since 2.18.0
     * @param string $document Published file name, e.g. `sitemap_index.xml`.
     * @return string Absolute view URL, or '' for a name that is not a sitemap file.
     */
    public static function view_url(string $document): string {
        $document = self::document_name($document);

        return $document === '' ? '' : self::view_prefix() . $document;
    }

    /**
     * The XML comment that points a sitemap's reader at its HTML view.
     *
     * A browser that no longer runs the stylesheet shows the raw XML tree, and
     * that tree shows comments. Returned empty when the URL cannot sit in a
     * comment at all: `--` is forbidden there, and an IDN host carries it.
     *
     * @since 2.18.0
     * @param string $document Published file name the comment should point at.
     * @return string Comment line, newline-terminated, or ''.
     */
    public static function view_comment(string $document): string {
        $url = self::view_url($document);

        if ($url === '' || strpos($url, '--') !== false || substr($url, -1) === '-') {
            return '';
        }

        return '<!-- Browse this sitemap: ' . esc_url_raw($url) . ' -->' . "\n";
    }

    /**
     * Add the view comment to a sitemap document about to be published.
     *
     * The comment names the document it sits in, so it is added where the
     * document's file name is known, at the write, rather than in the shared
     * prolog. It goes right after the `<?xml-stylesheet?>` instruction, which
     * is only there when styling is on, so a site with styling off gets no
     * comment, and a document that already carries one is left as it is.
     *
     * @since 2.18.0
     * @param string $xml      Sitemap XML.
     * @param string $document Published file name of that XML.
     * @return string
     */
    public static function with_view_comment(string $xml, string $document): string {
        if (strpos($xml, '<!-- Browse this sitemap: ') !== false) {
            return $xml;
        }

        $comment = self::view_comment($document);

        if ($comment === '') {
            return $xml;
        }

        return (string) preg_replace_callback(
            '/^<\?xml-stylesheet\b[^>]*\?>\R/m',
            static function (array $m) use ($comment): string {
                return $m[0] . $comment;
            },
            $xml,
            1
        );
    }

    /**
     * Everything of a view URL but the document name.
     *
     * @since 2.18.0
     * @return string
     */
    private static function view_prefix(): string {
        $base = home_url('/');

        return $base . (strpos($base, '?') === false ? '?' : '&') . self::VIEW_QUERY_VAR . '=';
    }

    /**
     * A requested document name, or '' when it is not one of ours to look up.
     *
     * Only a bare `*.xml` file name passes, so the value can never walk out of
     * the web root.
     *
     * @since 2.18.0
     * @param string $name Requested name.
     * @return string
     */
    private static function document_name(string $name): string {
        $name = trim($name);

        return preg_match('/^[A-Za-z0-9_-]+\.xml$/', $name) ? $name : '';
    }

    /**
     * Answer a request for a sitemap's HTML view.
     *
     * Gated exactly like the stylesheet: the view is the styled sitemap, so a
     * site that turned styling off gets neither.
     *
     * @since 2.18.0
     * @param \WP $wp Current WordPress environment instance.
     * @return void
     */
    public function maybe_serve_view($wp): void {
        if (is_admin() || !isset($wp->query_vars[self::VIEW_QUERY_VAR])) {
            return;
        }

        $requested = $wp->query_vars[self::VIEW_QUERY_VAR];
        $name      = is_string($requested) ? self::document_name($requested) : '';

        if ($name === '') {
            return;
        }

        $known = isset($_SERVER['HTTP_IF_NONE_MATCH'])
            ? trim(sanitize_text_field(wp_unslash($_SERVER['HTTP_IF_NONE_MATCH'])))
            : '';

        $response = $this->view_response($name, $this->settings(), $known);

        header('X-Robots-Tag: noindex, follow');

        if ($response['status'] === 404) {
            nocache_headers();
            status_header(404);
            exit;
        }

        // Validated rather than timed, like the stylesheet: the ETag changes
        // with the sitemap and with the branding, so a revisit costs a 304.
        header('Content-Type: text/html; charset=UTF-8');
        header('Cache-Control: public, max-age=0, must-revalidate');
        header('ETag: ' . $response['etag']);
        status_header($response['status']);

        if ($response['status'] === 304) {
            exit;
        }

        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- HTML produced by render_view(); every value in it is escaped there or by the XSLT processor.
        echo $response['html'];
        exit;
    }

    /**
     * The view of a sitemap document, from the cache when nothing changed.
     *
     * A sitemap page holds up to 50,000 URLs, and rendering it is a full parse
     * and an XSLT run (or a PHP-built table), on a public URL. So the rendered
     * page is kept, one entry per document, keyed by a fingerprint of all it
     * depends on: the document's XML, both branded stylesheets (palette, logo
     * and credit), which renderer runs, the home URL the index links against
     * and the plugin version. Anything changing misses the cache and replaces
     * the entry. The same fingerprint is the ETag, so a client holding the
     * current page gets a 304 without anything being rendered.
     *
     * @since 2.18.0
     * @param string $name          Document file name, already validated.
     * @param array  $settings      Sitemap settings.
     * @param string $if_none_match The request's If-None-Match, if any.
     * @return array{status: int, etag: string, html: string}
     */
    public function view_response(string $name, array $settings, string $if_none_match = ''): array {
        $missing = ['status' => 404, 'etag' => '', 'html' => ''];

        if (empty($settings['enabled']) || empty($settings['enable_styling'])) {
            return $missing;
        }

        $xml = $this->view_document($name, $settings);

        if ($xml === null || $xml === '') {
            return $missing;
        }

        $etag = '"' . md5(implode("\n", [
            md5($xml),
            md5($this->render($settings, 'sitemap')),
            md5($this->render($settings, 'index')),
            $this->xslt_available() ? 'xslt' : 'php',
            home_url('/'),
            defined('THINKRANK_VERSION') ? (string) THINKRANK_VERSION : '',
        ])) . '"';

        if ($if_none_match !== '' && $if_none_match === $etag) {
            return ['status' => 304, 'etag' => $etag, 'html' => ''];
        }

        $key    = self::VIEW_CACHE_PREFIX . md5($name);
        $cached = get_transient($key);

        if (is_array($cached) && ($cached['etag'] ?? '') === $etag && is_string($cached['html'] ?? null) && $cached['html'] !== '') {
            return ['status' => 200, 'etag' => $etag, 'html' => $cached['html']];
        }

        $html = $this->render_view($xml, $settings);

        if ($html === '') {
            return $missing;
        }

        set_transient($key, ['etag' => $etag, 'html' => $html], self::VIEW_CACHE_TTL);

        return ['status' => 200, 'etag' => $etag, 'html' => $html];
    }

    /**
     * The XML of a published sitemap document, read the way crawlers get it.
     *
     * Dynamic delivery renders (or reads the cached render of) the document;
     * static delivery reads the file in the web root. Either way only a name
     * the site publishes is looked up. `thinkrank_sitemap_view_document` lets
     * another plugin answer for sitemaps it serves itself, such as Pro's news
     * and video sitemaps.
     *
     * @since 2.18.0
     * @param string $name     Document file name.
     * @param array  $settings Sitemap settings.
     * @return string|null
     */
    protected function view_document(string $name, array $settings): ?string {
        /**
         * Supply the XML for a sitemap document ThinkRank itself does not publish.
         *
         * @since 2.18.0
         * @param string|null $xml      XML to render, or null to let ThinkRank look it up.
         * @param string      $name     Requested document file name.
         * @param array       $settings Sitemap settings.
         */
        $xml = apply_filters('thinkrank_sitemap_view_document', null, $name, $settings);

        if (is_string($xml) && $xml !== '') {
            return $xml;
        }

        $generator = new Sitemap_Generator(false);

        if (!$generator->publishes_document_name($name, $settings)) {
            return null;
        }

        if ('dynamic' === $generator->resolve_delivery_mode($settings)) {
            return $generator->render_document($name, $settings);
        }

        $path = ABSPATH . $name;

        if (!is_readable($path)) {
            return null;
        }

        // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local read of a sitemap file this plugin wrote to the web root.
        $xml = (string) file_get_contents($path);

        return $xml === '' ? null : $xml;
    }

    /**
     * Turn a sitemap document into the branded HTML page.
     *
     * The shipped stylesheet is run by PHP's XSLT processor when the `xsl`
     * extension is loaded, which keeps the page identical to the one browsers
     * used to draw. Without the extension, common on shared hosting, a PHP-built
     * page carries the same CSS, logo and credit.
     *
     * @since 2.18.0
     * @param string $xml      Sitemap XML.
     * @param array  $settings Sitemap settings.
     * @return string HTML, or '' when the XML is not a sitemap.
     */
    public function render_view(string $xml, array $settings): string {
        $doc = self::load_xml($xml);

        // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMDocument's own property name.
        $root = $doc === null ? null : $doc->documentElement;

        if (self::is_sitemap_element($root, 'sitemapindex')) {
            $variant = 'index';
        } elseif (self::is_sitemap_element($root, 'urlset')) {
            $variant = 'sitemap';
        } else {
            return '';
        }

        if ($this->xslt_available()) {
            $html = $this->transform($doc, $settings, $variant);

            if ($html !== '') {
                return $html;
            }
        }

        return $this->fallback_view($doc, $settings, $variant);
    }

    /**
     * Whether PHP can run the stylesheet itself. A seam for tests.
     *
     * @since 2.18.0
     * @return bool
     */
    protected function xslt_available(): bool {
        return class_exists('XSLTProcessor');
    }

    /**
     * Parse XML without touching the network or expanding entities.
     *
     * @since 2.18.0
     * @param string $xml XML source.
     * @return \DOMDocument|null
     */
    private static function load_xml(string $xml): ?\DOMDocument {
        if (trim($xml) === '' || !class_exists('DOMDocument')) {
            return null;
        }

        $doc      = new \DOMDocument();
        $previous = libxml_use_internal_errors(true);
        $loaded   = $doc->loadXML($xml, LIBXML_NONET);

        libxml_clear_errors();
        libxml_use_internal_errors($previous);

        return $loaded ? $doc : null;
    }

    /**
     * Run the branded stylesheet over the document on the server.
     *
     * @since 2.18.0
     * @param \DOMDocument $doc      Sitemap document.
     * @param array        $settings Sitemap settings.
     * @param string       $variant  `sitemap` or `index`.
     * @return string HTML, or '' on any failure, so the caller can fall back.
     */
    private function transform(\DOMDocument $doc, array $settings, string $variant): string {
        $sheet = self::load_xml($this->render($settings, $variant));

        if ($sheet === null) {
            return '';
        }

        $previous = libxml_use_internal_errors(true);

        try {
            $processor = new \XSLTProcessor();
            $processor->importStylesheet($sheet);

            if ($variant === 'index') {
                $processor->setParameter('', 'thinkrank_home', home_url('/'));
                $processor->setParameter('', 'thinkrank_view', self::view_prefix());
            }

            $html = $processor->transformToXml($doc);
        } catch (\Throwable $e) {
            $html = false;
        }

        libxml_clear_errors();
        libxml_use_internal_errors($previous);

        if (!is_string($html) || trim($html) === '') {
            return '';
        }

        // libxslt's html output opens with an HTML 4.0 doctype; the page is
        // written for standards mode.
        return "<!DOCTYPE html>\n" . ltrim((string) preg_replace('/^\s*<!DOCTYPE[^>]*>/i', '', $html, 1));
    }

    /**
     * The HTML view built in PHP, for hosts without the `xsl` extension.
     *
     * Reuses the template's own `<style>` block, so the branding and the layout
     * classes are the stylesheet's, not a second copy of them.
     *
     * @since 2.18.0
     * @param \DOMDocument $doc      Sitemap document.
     * @param array        $settings Sitemap settings.
     * @param string       $variant  `sitemap` or `index`.
     * @return string HTML.
     */
    private function fallback_view(\DOMDocument $doc, array $settings, string $variant): string {
        $template = $this->render($settings, $variant);
        $style    = preg_match('#<style type="text/css">.*?</style>#s', $template, $m) ? $m[0] : '';
        $credit   = (bool) apply_filters('thinkrank_show_credit', true, 'sitemap', $variant);
        $is_index = $variant === 'index';
        $title    = $is_index ? 'XML Sitemap Index' : 'XML Sitemap';
        $rows     = $is_index ? $this->index_rows($doc) : $this->url_rows($doc);

        $html  = "<!DOCTYPE html>\n<html>\n<head>\n<meta charset=\"utf-8\"/>\n";
        $html .= '<meta name="robots" content="noindex, follow"/>' . "\n";
        $html .= '<title>' . esc_html($title) . ' - ThinkRank SEO</title>' . "\n" . $style . "\n</head>\n<body>\n";
        $html .= '<div class="header">' . $this->logo_markup($settings);
        $html .= '<h1>' . esc_html($title) . '</h1>';
        $html .= $credit ? '<p>Generated by ThinkRank SEO Plugin</p>' : '';
        $html .= '<div class="stats"><div class="stat-item"><span class="stat-number">' . count($rows['rows']) . '</span>';
        $html .= '<span class="stat-label">' . ($is_index ? 'Total Sitemaps' : 'Total URLs') . '</span></div></div></div>' . "\n";
        $html .= '<div class="container"><div class="table-header"><h2>' . ($is_index ? 'Individual Sitemaps' : 'Sitemap URLs') . '</h2></div>';
        $html .= '<table><thead><tr>';

        foreach ($rows['head'] as $heading) {
            $html .= '<th>' . esc_html($heading) . '</th>';
        }

        $html .= '</tr></thead><tbody>' . "\n" . implode("\n", $rows['rows']) . "\n</tbody></table></div>\n";
        $html .= '<div class="footer"><p>This XML sitemap is used by search engines to better understand your website structure.</p>';
        $html .= $credit ? '<p>Generated by <a href="https://wordpress.org/plugins/thinkrank/" target="_blank">ThinkRank SEO</a></p>' : '';
        $html .= "</div>\n</body>\n</html>\n";

        return $html;
    }

    /**
     * Table rows for a `<urlset>`, highest priority first as the stylesheet sorts.
     *
     * @since 2.18.0
     * @param \DOMDocument $doc Sitemap document.
     * @return array{head: string[], rows: string[]}
     */
    private function url_rows(\DOMDocument $doc): array {
        $entries = [];

        // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMDocument's own property names.
        foreach ($doc->documentElement->childNodes as $node) {
            if (!self::is_sitemap_element($node, 'url')) {
                continue;
            }

            $entries[] = [
                'loc'        => self::child_text($node, 'loc'),
                'lastmod'    => substr(self::child_text($node, 'lastmod'), 0, 10),
                'priority'   => self::child_text($node, 'priority'),
                'changefreq' => self::child_text($node, 'changefreq'),
            ];
        }

        usort($entries, static function (array $a, array $b): int {
            return (float) $b['priority'] <=> (float) $a['priority'];
        });

        $rows = [];

        foreach ($entries as $entry) {
            $priority = (float) $entry['priority'];
            $class    = $priority >= 0.8 ? 'priority-high' : ($priority >= 0.5 ? 'priority-medium' : 'priority-low');

            $rows[] = '<tr><td class="url-cell"><a href="' . esc_url($entry['loc']) . '" target="_blank">' . esc_html($entry['loc']) . '</a></td>'
                . '<td class="lastmod">' . esc_html($entry['lastmod']) . '</td>'
                . '<td class="' . $class . '">' . esc_html($entry['priority']) . '</td>'
                . '<td><span class="changefreq">' . esc_html($entry['changefreq']) . '</span></td></tr>';
        }

        return [
            'head' => ['URL', 'Last Modified', 'Priority', 'Change Frequency'],
            'rows' => $rows,
        ];
    }

    /**
     * Table rows for a `<sitemapindex>`, each child linked to its own view.
     *
     * @since 2.18.0
     * @param \DOMDocument $doc Sitemap index document.
     * @return array{head: string[], rows: string[]}
     */
    private function index_rows(\DOMDocument $doc): array {
        $home = home_url('/');
        $rows = [];

        // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMDocument's own property names.
        foreach ($doc->documentElement->childNodes as $node) {
            if (!self::is_sitemap_element($node, 'sitemap')) {
                continue;
            }

            $loc     = self::child_text($node, 'loc');
            $lastmod = substr(self::child_text($node, 'lastmod'), 0, 10);
            $href    = $loc;

            if (strpos($loc, $home) === 0) {
                $view = self::view_url(substr($loc, strlen($home)));
                $href = $view !== '' ? $view : $loc;
            }

            $rows[] = '<tr><td class="sitemap-cell"><a href="' . esc_url($href) . '" target="_blank">' . esc_html($loc) . '</a></td>'
                . '<td class="lastmod">' . esc_html($lastmod !== '' ? $lastmod : '-') . '</td></tr>';
        }

        return [
            'head' => ['Sitemap URL', 'Last Modified'],
            'rows' => $rows,
        ];
    }

    /**
     * Text of an element's first direct child in the sitemap namespace.
     *
     * @since 2.18.0
     * @param \DOMElement $element Parent element.
     * @param string      $name    Local name.
     * @return string
     */
    private static function child_text(\DOMElement $element, string $name): string {
        // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMNode's own property name.
        foreach ($element->childNodes as $node) {
            if (self::is_sitemap_element($node, $name)) {
                // phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMNode's own property name.
                return trim((string) $node->textContent);
            }
        }

        return '';
    }

    /**
     * Whether a node is the named element in the sitemap namespace.
     *
     * @since 2.18.0
     * @param \DOMNode|null $node Node to test.
     * @param string        $name Local name.
     * @return bool
     */
    private static function is_sitemap_element(?\DOMNode $node, string $name): bool {
        // phpcs:disable WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOMNode's own property names.
        return $node instanceof \DOMElement
            && $node->namespaceURI === self::SITEMAP_NS
            && $node->localName === $name;
        // phpcs:enable
    }

    /**
     * Answer a stylesheet request.
     *
     * @since 2.7.0
     * @param \WP $wp Current WordPress environment instance.
     * @return void
     */
    public function maybe_serve($wp): void {
        if (is_admin()) {
            return;
        }

        $variant = isset($wp->query_vars[self::QUERY_VAR])
            ? sanitize_key((string) $wp->query_vars[self::QUERY_VAR])
            : '';

        if ($variant === '' || !isset(self::VARIANTS[$variant])) {
            return;
        }

        $settings = $this->settings();

        // Styling is opt-in, and turning it off stops the prolog writing the
        // instruction at all. Serving a stylesheet the site has switched off
        // would only paint sitemaps published before the change.
        if (empty($settings['enabled']) || empty($settings['enable_styling'])) {
            status_header(404);
            nocache_headers();
            exit;
        }

        $xsl = $this->render($settings, $variant);

        if ($xsl === '') {
            status_header(404);
            nocache_headers();
            exit;
        }

        // Validated rather than timed. The URL in a published sitemap is fixed,
        // so a freshness window is a window in which a colour the owner just
        // saved is not the colour they see, with nothing they can do but wait
        // it out; a plain `max-age` of an hour had exactly that effect while
        // this was being built. Revalidating every time costs a 304.
        $etag = '"' . md5($xsl) . '"';

        header('Content-Type: text/xsl; charset=UTF-8');
        header('X-Robots-Tag: noindex');
        header('Cache-Control: public, max-age=0, must-revalidate');
        header('ETag: ' . $etag);

        $known = isset($_SERVER['HTTP_IF_NONE_MATCH'])
            ? trim(sanitize_text_field(wp_unslash($_SERVER['HTTP_IF_NONE_MATCH'])))
            : '';

        if ($known !== '' && $known === $etag) {
            status_header(304);
            exit;
        }

        status_header(200);

        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- XSL document assembled and escaped in render().
        echo $xsl;
        exit;
    }

    /**
     * Build the stylesheet for a variant with the site's branding applied.
     *
     * @since 2.7.0
     * @param array  $settings Sitemap settings.
     * @param string $variant  One of the VARIANTS keys.
     * @return string XSL document, or '' when the template is unreadable.
     */
    public function render(array $settings, string $variant): string {
        if (!isset(self::VARIANTS[$variant])) {
            return '';
        }

        $path = THINKRANK_PLUGIN_DIR . 'static/xsl/' . self::VARIANTS[$variant];

        if (!is_readable($path)) {
            return '';
        }

        // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local read of a fixed file shipped with the plugin.
        $xsl = (string) file_get_contents($path);

        if ($xsl === '') {
            return '';
        }

        foreach ($this->palette($settings) as $property => $value) {
            $xsl = self::set_custom_property($xsl, $property, $value);
        }

        $xsl = $this->apply_credit($xsl, $variant);

        $logo = $this->logo_markup($settings);

        if ($logo === '') {
            // Take the whole line, not just the marker: an XSLT processor drops
            // the comment either way, but leaving a stray indented blank line
            // in a document people do read is needless.
            return (string) preg_replace(
                '/^[ \t]*' . preg_quote(self::LOGO_MARKER, '/') . '\R/m',
                '',
                $xsl,
                1
            );
        }

        return str_replace(self::LOGO_MARKER, $logo, $xsl);
    }

    /**
     * Keep or drop the "Generated by ThinkRank SEO" lines.
     *
     * Shown by default. A site that wants them gone returns false from
     * `thinkrank_show_credit`, and every line carrying the credit marker is
     * removed whole. Kept, the marker is a comment the XSLT processor strips.
     *
     * @since 2.15.0
     * @param string $xsl     Stylesheet source.
     * @param string $variant One of the VARIANTS keys.
     * @return string
     */
    private function apply_credit(string $xsl, string $variant): string {
        /**
         * Filter whether ThinkRank's "Generated by" credit is printed.
         *
         * @since 2.15.0
         * @param bool   $show    Whether to print the credit. Default true.
         * @param string $context Where it is printed: 'sitemap' or 'llms_txt'.
         * @param string $variant The sitemap stylesheet variant ('sitemap' or
         *                        'index'); '' for llms.txt.
         */
        if ((bool) apply_filters('thinkrank_show_credit', true, 'sitemap', $variant)) {
            return $xsl;
        }

        return (string) preg_replace(
            '/^[ \t]*' . preg_quote(self::CREDIT_MARKER, '/') . '.*\R/m',
            '',
            $xsl
        );
    }

    /**
     * The custom property overrides a site's chosen colours imply.
     *
     * A colour is never simply pasted everywhere it appears. Where it becomes
     * a background the text on top is recomputed for it, and where it becomes
     * text on the page's own white it is darkened until it is readable there.
     * A branding feature that lets an owner pick pale yellow and hands back a
     * sitemap nobody can read is worse than one with no branding at all.
     *
     * An unset colour contributes nothing, which is what keeps an untouched
     * site rendering exactly as it did.
     *
     * @since 2.7.0
     * @param array $settings Sitemap settings.
     * @return array<string, string> Property name => value.
     */
    private function palette(array $settings): array {
        $main   = self::hex($settings['styling_color_main'] ?? '');
        $accent = self::hex($settings['styling_color_accent'] ?? '');

        if ($main === '' && $accent === '') {
            return [];
        }

        $values = [];

        if ($main !== '') {
            // Backgrounds and rules take the colour as picked.
            $values['--tr-brand-main']    = $main;
            $values['--tr-brand-th']      = $main;
            $values['--tr-brand-rule']    = $main;
            $values['--tr-brand-note-bg'] = self::tint($main);

            // Text on those backgrounds is chosen to sit on them.
            $values['--tr-brand-th-text'] = self::readable_ink([$main]);

            // Text on the page itself is darkened to stay legible on white.
            $values['--tr-brand-link'] = self::readable_on_paper($main);
            $values['--tr-brand-note'] = self::readable_on_paper($main);
        }

        if ($accent !== '') {
            $values['--tr-brand-accent']     = $accent;
            $values['--tr-brand-badge']      = $accent;
            $values['--tr-brand-badge-text'] = self::readable_ink([$accent]);
            $values['--tr-brand-link-hover'] = self::readable_on_paper($accent);
        }

        // The header is a gradient, so its text has to clear both stops. An
        // unset colour still contributes the stock one it will render as.
        $values['--tr-brand-on-brand'] = self::readable_ink([
            $main !== '' ? $main : self::STOCK_PALETTE['main'],
            $accent !== '' ? $accent : self::STOCK_PALETTE['accent'],
        ]);

        return $values;
    }

    /**
     * Overwrite one custom property declaration, leaving everything else alone.
     *
     * Deliberately narrow: it rewrites the value of a `--tr-*` declaration that
     * is already in the template and does nothing when that declaration is
     * absent. A template edited past recognition therefore renders stock rather
     * than broken.
     *
     * @since 2.7.0
     * @param string $xsl      Stylesheet source.
     * @param string $property Custom property name, leading dashes included.
     * @param string $value    Replacement value.
     * @return string
     */
    private static function set_custom_property(string $xsl, string $property, string $value): string {
        return (string) preg_replace(
            '/(' . preg_quote($property, '/') . '\s*:\s*)[^;]+/',
            '${1}' . $value,
            $xsl,
            1
        );
    }

    /**
     * The `<img>` that replaces the logo marker, or '' to leave it stripped.
     *
     * @since 2.7.0
     * @param array $settings Sitemap settings.
     * @return string XML-safe markup.
     */
    private function logo_markup(array $settings): string {
        if (empty($settings['styling_logo'])) {
            return '';
        }

        $url = (string) ($settings['styling_logo_url'] ?? '');

        // Nothing picked means the site icon, which is the logo a site has
        // already told WordPress about.
        if (trim($url) === '') {
            $url = (string) get_site_icon_url(192);
        }

        // esc_url_raw() for the protocol allow-list, which is the part that
        // matters for safety, and no display escaping of its own.
        $url = esc_url_raw($url);

        if ($url === '') {
            return '';
        }

        // Escaped for XML explicitly rather than by esc_url()/esc_attr(). Those
        // escape for HTML, where a bare `&` in a query string is tolerated; here
        // the markup is spliced into an XML document, and one unescaped
        // ampersand in a logo URL takes the whole sitemap view down rather than
        // just looking wrong.
        return sprintf(
            '<img class="sitemap-logo" src="%s" alt="%s"/>',
            self::xml_attr($url),
            self::xml_attr((string) get_bloginfo('name'))
        );
    }

    /**
     * Escape a value for an XML attribute.
     *
     * @since 2.7.0
     * @param string $value Raw value.
     * @return string
     */
    private static function xml_attr(string $value): string {
        return htmlspecialchars($value, ENT_QUOTES | ENT_XML1, 'UTF-8');
    }

    /**
     * Black or white, whichever is legible on these backgrounds.
     *
     * A single background is answered by luminance alone: 0.45 sits between
     * the luminance of a mid grey and a light one, which is where white text
     * stops being readable.
     *
     * The header is a gradient, and a gradient can span a dark stop and a
     * light one. Then no flat ink clears AA on both, and the luminance test
     * alone answers the lightest stop while ignoring the other: navy to cyan
     * picked near-black, which reads at 1.22:1 where the heading actually
     * starts. For more than one stop the ink is therefore judged against its
     * hardest stop, which is what this was always documented to do.
     *
     * @since 2.7.0
     * @param string[] $colours Hex colours, `#rrggbb`.
     * @return string `#ffffff` or `#111111`.
     */
    private static function readable_ink(array $colours): string {
        $lightest = 0.0;

        foreach ($colours as $colour) {
            $lightest = max($lightest, self::luminance($colour));
        }

        $ink = $lightest > 0.45 ? '#111111' : '#ffffff';

        if (count($colours) < 2) {
            return $ink;
        }

        $other = '#111111' === $ink ? '#ffffff' : '#111111';

        // Strictly better, never merely different: the alternative has to beat
        // the luminance test's answer at its worst stop to displace it, so a
        // gradient both inks handle keeps the ink it has always been given.
        return self::worst_contrast($other, $colours) > self::worst_contrast($ink, $colours)
            ? $other
            : $ink;
    }

    /**
     * The lowest WCAG contrast ratio an ink reaches across several backgrounds.
     *
     * @since 2.7.0
     * @param string   $ink     Hex colour the text is drawn in.
     * @param string[] $colours Hex backgrounds it has to sit on.
     * @return float Contrast ratio, 1.0 when there is nothing to sit on.
     */
    private static function worst_contrast(string $ink, array $colours): float {
        $worst = null;

        foreach ($colours as $colour) {
            $high = max(self::luminance($ink), self::luminance($colour));
            $low  = min(self::luminance($ink), self::luminance($colour));

            $ratio = ($high + 0.05) / ($low + 0.05);
            $worst = null === $worst ? $ratio : min($worst, $ratio);
        }

        return null === $worst ? 1.0 : $worst;
    }

    /**
     * The same colour, darkened until it is readable as text on white.
     *
     * Links, and the note panel's body text, sit on the page's own background
     * rather than on the brand colour, so a pale brand has to be brought down
     * to meet it. Returned unchanged when it already clears WCAG AA.
     *
     * @since 2.7.0
     * @param string $colour Hex colour, `#rrggbb`.
     * @return string Hex colour.
     */
    private static function readable_on_paper(string $colour): string {
        // Contrast against white is 1.05 / (L + 0.05); AA body text wants 4.5.
        $ceiling = (1.05 / 4.5) - 0.05;

        if (self::luminance($colour) <= $ceiling) {
            return $colour;
        }

        $hex = ltrim($colour, '#');

        if (strlen($hex) !== 6) {
            return $colour;
        }

        $channels = [
            (int) hexdec(substr($hex, 0, 2)),
            (int) hexdec(substr($hex, 2, 2)),
            (int) hexdec(substr($hex, 4, 2)),
        ];

        // Scale the channels down together so the hue survives the darkening,
        // in small steps so the result clears the bar without overshooting it
        // into something near-black the owner would not recognise.
        for ($factor = 0.98; $factor > 0.0; $factor -= 0.02) {
            $candidate = '#';

            foreach ($channels as $channel) {
                $candidate .= str_pad(dechex((int) round($channel * $factor)), 2, '0', STR_PAD_LEFT);
            }

            if (self::luminance($candidate) <= $ceiling) {
                return $candidate;
            }
        }

        return '#111111';
    }

    /**
     * A colour mixed most of the way into white.
     *
     * Computed here rather than left to CSS `color-mix()`, so the value in the
     * served stylesheet is a plain hex and the template stays renderable by
     * anything that can read the stock one.
     *
     * @since 2.7.0
     * @param string $colour Hex colour, `#rrggbb`.
     * @return string Hex colour.
     */
    private static function tint(string $colour): string {
        $hex = ltrim($colour, '#');

        if (strlen($hex) !== 6) {
            return $colour;
        }

        $out = '#';

        foreach ([0, 2, 4] as $offset) {
            $channel = (int) hexdec(substr($hex, $offset, 2));
            $out    .= str_pad(dechex((int) round(255 - ((255 - $channel) * 0.10))), 2, '0', STR_PAD_LEFT);
        }

        return $out;
    }

    /**
     * WCAG relative luminance of a hex colour, 0 (black) to 1 (white).
     *
     * @since 2.7.0
     * @param string $colour Hex colour, `#rrggbb`.
     * @return float
     */
    private static function luminance(string $colour): float {
        $hex = ltrim($colour, '#');

        if (strlen($hex) === 3) {
            $hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
        }

        if (strlen($hex) !== 6) {
            return 0.0;
        }

        $channels = [];

        foreach ([0, 2, 4] as $offset) {
            $value      = hexdec(substr($hex, $offset, 2)) / 255;
            $channels[] = $value <= 0.03928
                ? $value / 12.92
                : pow(($value + 0.055) / 1.055, 2.4);
        }

        return (0.2126 * $channels[0]) + (0.7152 * $channels[1]) + (0.0722 * $channels[2]);
    }

    /**
     * A stored colour, normalized, or '' when it is not one.
     *
     * '' is the meaningful default: it means "substitute nothing", so the
     * template's own value stands and an untouched site renders byte for byte
     * as it did before this feature existed.
     *
     * @since 2.7.0
     * @param mixed $value Stored setting value.
     * @return string `#rrggbb`, or ''.
     */
    public static function hex($value): string {
        if (!is_string($value)) {
            return '';
        }

        $value = trim($value);

        if ($value === '') {
            return '';
        }

        if ($value[0] !== '#') {
            $value = '#' . $value;
        }

        $colour = sanitize_hex_color(strtolower($value));

        return is_string($colour) ? $colour : '';
    }

    /**
     * Stored sitemap settings.
     *
     * @since 2.7.0
     * @return array
     */
    private function settings(): array {
        return (new Sitemap_Generator(false))->get_settings('site', null);
    }
