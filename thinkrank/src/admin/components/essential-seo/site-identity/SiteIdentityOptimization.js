const IconInfo = () => (
	<svg
		width="14"
		height="14"
		viewBox="0 0 24 24"
		fill="none"
		stroke="currentColor"
		strokeWidth="2.5"
		strokeLinecap="round"
		strokeLinejoin="round"
	>
		<circle cx="12" cy="12" r="10" />
		<line x1="12" y1="16" x2="12" y2="12" />
		<line x1="12" y1="8" x2="12.01" y2="8" />
	</svg>
);

/**
 * Get sub-section specific display name for notices
 * @param activeSubSection
 */
const getSubSectionDisplayName = (activeSubSection) => {
	const subSectionNames = {
		'basic-info': __('Basic Info', 'thinkrank'),
		'title-formats': __('Title Formats', 'thinkrank'),
		breadcrumbs: __('Breadcrumbs', 'thinkrank'),
		'robots-txt': __('Robots.txt', 'thinkrank'),
		'site-assets': __('Site Assets', 'thinkrank'),
	};
	return (
		subSectionNames[activeSubSection] || __('Site Identity', 'thinkrank')
	);
};

const SiteIdentityOptimization = ({
	optimizationResults,
	activeSubSection,
	settings,
	handleSettingChange,
	setOptimizationResults,
}) => {
	const sectionMap = {
		'basic-info': 'all',
		'title-formats': 'title_formats',
		breadcrumbs: 'breadcrumbs',
		'hero-section': 'hero_section',
		'local-seo': 'local_seo',
	};
	const currentSectionKey = sectionMap[activeSubSection] || 'all';
	const currentResults = optimizationResults[currentSectionKey];

	if (!currentResults) {
		return null;
	}

	const scoreConfig = (score) => {
		if (score >= 80)
			return {
				cardBg: 'tr-bg-success-bg tr-border tr-border-success',
				scoreText: 'tr-text-success',
			};
		if (score >= 60)
			return {
				cardBg: 'tr-bg-warning-bg tr-border tr-border-warning',
				scoreText: 'tr-text-warning',
			};
		return {
			cardBg: 'tr-bg-danger-bg tr-border tr-border-danger',
			scoreText: 'tr-text-danger',
		};
	};

	const overallScoreConfig =
		currentResults.score !== undefined
			? scoreConfig(currentResults.score)
			: null;

	const handleApply = () => {
		Object.keys(currentResults.optimized_data).forEach((key) => {
			if (settings.hasOwnProperty(key)) {
				handleSettingChange(key, currentResults.optimized_data[key]);
			}
		});
		notify.success(
			activeSubSection === 'basic-info'
				? __(
						'AI optimization suggestions applied successfully!',
						'thinkrank'
					)
				: __(
						`${getSubSectionDisplayName(activeSubSection)} optimization suggestions applied successfully!`,
						'thinkrank'
					)
		);
		setOptimizationResults((prev) => {
			const updated = { ...prev };
			delete updated[currentSectionKey];
			return updated;
		});
	};

	const handleDismiss = () => {
		setOptimizationResults((prev) => {
			const updated = { ...prev };
			delete updated[currentSectionKey];
			return updated;
		});
	};

	return (
		<Card padding={false} className="tr-mt-4">
			{/* Header */}
			<div className="tr-px-5 tr-py-4 tr-border-b tr-border-secondary tr-flex tr-items-center tr-justify-between">
				<div>
					<h3 className="tr-text-sm tr-font-semibold tr-text-primary tr-m-0">
						{activeSubSection === 'basic-info'
							? __('Rule-Based Optimization Results', 'thinkrank')
							: __('Section Optimization Results', 'thinkrank')}
					</h3>
					{currentResults.ai_model && (
						<p className="tr-text-xs tr-text-tertiary tr-m-0 tr-mt-0.5">
							{__('Generated by:', 'thinkrank')}{' '}
							{currentResults.ai_model}
						</p>
					)}
				</div>
				{/* Score badge */}
				{currentResults.score !== undefined && (
					<span
						className={`tr-inline-flex tr-items-center tr-gap-1.5 tr-text-xs tr-font-medium tr-px-2.5 tr-py-1 tr-rounded-full tr-border ${overallScoreConfig.cardBg} ${overallScoreConfig.scoreText}`}
					>
						{__('Score:', 'thinkrank')} {currentResults.score}/100
					</span>
				)}
			</div>

			<div className="tr-p-5 tr-flex tr-flex-col tr-gap-5">
				{/* Section Scores */}
				{currentResults.section_scores &&
					Object.keys(currentResults.section_scores).length > 0 && (
						<div>
							<p className="tr-text-xs tr-font-semibold tr-text-secondary tr-uppercase tr-tracking-wide tr-m-0 tr-mb-2">
								{__('Section Scores', 'thinkrank')}
							</p>
							<div className="tr-grid tr-grid-cols-2 tr-gap-2">
								{Object.entries(currentResults.section_scores)
									.filter(([section]) => {
										if (activeSubSection === 'basic-info') {
											return true;
										}
										const filterMap = {
											'title-formats': 'title_formats',
											breadcrumbs: 'breadcrumbs',
											'hero-section': 'hero_section',
											'local-seo': 'local_seo',
										};
										return (
											section ===
											filterMap[activeSubSection]
										);
									})
									.map(([section, score]) => {
										const cfg = scoreConfig(score);
										return (
											<div
												key={section}
												className={`tr-px-3 tr-py-2 tr-rounded tr-text-xs ${cfg.cardBg}`}
											>
												<span className="tr-font-semibold tr-text-secondary tr-block tr-mb-0.5">
													{section
														.replace(/_/g, ' ')
														.replace(/\b\w/g, (l) =>
															l.toUpperCase()
														)}
												</span>
												<span
													className={`tr-font-bold ${cfg.scoreText}`}
												>
													{score}/100
												</span>
											</div>
										);
									})}
							</div>
						</div>
					)}

				{/* Warnings */}
				{currentResults.warnings &&
					currentResults.warnings.length > 0 && (
						<div>
							<p className="tr-text-xs tr-font-semibold tr-text-secondary tr-uppercase tr-tracking-wide tr-m-0 tr-mb-2">
								{__('Warnings', 'thinkrank')}
							</p>
							<div className="tr-flex tr-flex-col tr-gap-1.5">
								{currentResults.warnings.map((warning, i) => (
									<div
										key={i}
										className="tr-bg-warning-bg tr-text-warning tr-flex tr-items-start tr-gap-2 tr-px-3 tr-py-2 tr-rounded tr-text-xs"
									>
										<span className="tr-shrink-0 tr-mt-0.5">
											<IconWarning />
										</span>
										<span>{warning}</span>
									</div>
								))}
							</div>
						</div>
					)}

				{/* Suggestions */}
				{currentResults.suggestions &&
					currentResults.suggestions.length > 0 && (
						<div>
							<p className="tr-text-xs tr-font-semibold tr-text-secondary tr-uppercase tr-tracking-wide tr-m-0 tr-mb-2">
								{__('Optimization Suggestions', 'thinkrank')}
							</p>
							<div className="tr-flex tr-flex-col tr-gap-1.5">
								{currentResults.suggestions.map(
									(suggestion, i) => (
										<div
											key={i}
											className="tr-bg-brand-bg tr-text-brand tr-flex tr-items-start tr-gap-2 tr-px-3 tr-py-2 tr-rounded tr-text-xs"
										>
											<span className="tr-shrink-0 tr-mt-0.5">
												<IconInfo />
											</span>
											<span>{suggestion}</span>
										</div>
									)
								)}
							</div>
						</div>
					)}

				{/* Suggested Changes */}
				{currentResults.optimized_data &&
					Object.keys(currentResults.optimized_data).length > 0 && (
						<div>
							<p className="tr-text-xs tr-font-semibold tr-text-secondary tr-uppercase tr-tracking-wide tr-m-0 tr-mb-2">
								{__('Suggested Changes', 'thinkrank')}
							</p>
							<div className="tr-bg-white tr-rounded tr-px-3 tr-py-3 tr-flex tr-flex-col tr-gap-2">
								{Object.keys(currentResults.optimized_data).map(
									(key) => (
										<div key={key} className="tr-text-xs">
											<span className="tr-font-semibold tr-text-secondary">
												{key
													.replace(/_/g, ' ')
													.replace(/\b\w/g, (l) =>
														l.toUpperCase()
													)}
												:
											</span>
											<span className="tr-text-tertiary tr-ml-1">
												{
													currentResults
														.optimized_data[key]
												}
											</span>
										</div>
									)
								)}
							</div>
						</div>
					)}

				{/* Action Buttons */}
				{currentResults.optimized_data &&
					Object.keys(currentResults.optimized_data).length > 0 && (
						<div className="tr-flex tr-items-center tr-gap-2">
							<Button
								variant="primary"
								size="md"
								onClick={handleApply}
							>
								{activeSubSection === 'basic-info'
									? __('Apply AI Suggestions', 'thinkrank')
									: __(
											'Apply Optimization Results',
											'thinkrank'
										)}
							</Button>
							<Button
								variant="secondary"
								size="md"
								onClick={handleDismiss}
							>
								{__('Dismiss', 'thinkrank')}
							</Button>
						</div>
					)}
			</div>
		</Card>
	);
};

export default SiteIdentityOptimization;
